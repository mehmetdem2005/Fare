# Video-exact Blender Sapling Tree Gen build.
# Shorts: z2hsTlHbOpw and ZNv-MpvXiiY.
# Source preset: blender/blender-addons/add_curve_sapling/presets/small_pine.py
# Changes explicitly shown: Show Leaves, leafScale=.41, leafScaleX=.05, Levels=3.
import ast
import json
import os
import sys
import bpy

ADDON_DIR = os.environ.get("SAPLING_ADDON_DIR", "/tmp/blender_addons")
sys.path.insert(0, ADDON_DIR)
import add_curve_sapling
add_curve_sapling.register()

bpy.ops.object.select_all(action="SELECT")
bpy.ops.object.delete(use_global=False)
with open(os.path.join(ADDON_DIR, "add_curve_sapling", "presets", "small_pine.py"), encoding="utf-8") as f:
    preset = next(ast.literal_eval(line) for line in f if line.strip() and not line.startswith("#"))

# These are the actual operator properties from the video, not a visual approximation.
preset["showLeaves"] = True
preset["leafShape"] = "rect"
preset["leaves"] = 500
preset["leafScale"] = 0.41
preset["leafScaleX"] = 0.05
preset["levels"] = 3
preset["seed"] = 0
preset["makeMesh"] = False
preset["useArm"] = False
preset["wind"] = 0.0
preset["leafAnim"] = False

allowed = set(bpy.ops.curve.tree_add.get_rna_type().properties.keys())
props = {k: v for k, v in preset.items() if k in allowed and k not in {"rna_type"}}
unknown = sorted(set(preset) - allowed)
print("SAPLING_OPERATOR_PROPERTIES", len(props), "ignored_preset_options", unknown)
print("VIDEO_PARAMETERS", json.dumps({k: preset[k] for k in ["showLeaves","leafShape","leaves","leafScale","leafScaleX","levels","seed","scale","nrings"]}))
result = bpy.ops.curve.tree_add("EXEC_DEFAULT", **props)
if "FINISHED" not in result:
    raise RuntimeError("Actual Blender Sapling operator failed: " + str(result))

objs = list(bpy.context.scene.objects)
print("SAPLING_RAW_OBJECTS", [(o.name, o.type) for o in objs])
if not objs:
    raise RuntimeError("Sapling generated no objects")

# Turn Sapling's actual curve geometry into portable triangle meshes.
for obj in list(bpy.context.scene.objects):
    if obj.type == "CURVE":
        bpy.ops.object.select_all(action="DESELECT")
        obj.select_set(True)
        bpy.context.view_layer.objects.active = obj
        bpy.ops.object.convert(target="MESH")

wood = bpy.data.materials.new("Sapling_Pine_Bark")
wood.use_nodes = True
wood.diffuse_color = (0.245,0.143,0.085,1)
wood.node_tree.nodes.get("Principled BSDF").inputs["Base Color"].default_value = (0.245,0.143,0.085,1)
wood.node_tree.nodes.get("Principled BSDF").inputs["Roughness"].default_value = 0.92
wood.use_backface_culling = False

needle = bpy.data.materials.new("Sapling_Real_Needles")
needle.use_nodes = True
needle.diffuse_color = (0.18,0.31,0.10,1)
needle.node_tree.nodes.get("Principled BSDF").inputs["Base Color"].default_value = (0.20,0.38,0.11,1)
needle.node_tree.nodes.get("Principled BSDF").inputs["Roughness"].default_value = 0.94
needle.use_backface_culling = False

vertex_total=0
face_total=0
for obj in bpy.context.scene.objects:
    if obj.type != "MESH":
        continue
    is_leaf = "leave" in obj.name.lower() or "leaf" in obj.name.lower()
    obj.data.materials.clear()
    obj.data.materials.append(needle if is_leaf else wood)
    obj.name = "Sapling_Needles" if is_leaf else "Sapling_Branches_Trunk"
    vertex_total += len(obj.data.vertices)
    face_total += len(obj.data.polygons)
print("SAPLING_GENERATED_MESH", vertex_total,face_total)

if vertex_total < 500 or face_total < 200:
    raise RuntimeError("Sapling generated too little geometry")

output_dir = os.environ.get("SAPLING_OUTPUT_DIR", "/tmp/sapling_output")
os.makedirs(output_dir, exist_ok=True)
bpy.ops.object.select_all(action="DESELECT")
for obj in bpy.context.scene.objects:
    if obj.type == "MESH":
        obj.select_set(True)
# Export exact generated meshes, retaining object hierarchy and materials.
bpy.ops.export_scene.gltf(filepath=os.path.join(output_dir,"sapling_pine.glb"),export_format="GLB",export_apply=True,use_selection=True)
bpy.ops.wm.save_as_mainfile(filepath=os.path.join(output_dir,"sapling_small_pine_exact.blend"))
with open(os.path.join(output_dir,"recipe.json"),"w",encoding="utf-8") as f:
    json.dump({"source_videos":["z2hsTlHbOpw","ZNv-MpvXiiY"],"sapling_preset":"small_pine.py","video_settings":{k:preset[k] for k in ["showLeaves","leafShape","leaves","leafScale","leafScaleX","levels","seed","scale","nrings"]},"vertices":vertex_total,"faces":face_total,"source":"Blender Sapling Tree Gen; generated by real Blender operator"}, f, indent=2)
print("SAPLING_VIDEO_EXACT_OK", vertex_total, face_total,os.path.getsize(os.path.join(output_dir,"sapling_pine.glb")))
